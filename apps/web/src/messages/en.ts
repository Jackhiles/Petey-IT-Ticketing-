export type Messages = typeof en;

/** Turns an error code from packages/core into a message, falling back to a generic one. */
export function errorMessage(code: string | undefined): string | undefined {
  if (!code) return undefined;
  const errors: Record<string, string> = en.errors;
  return errors[code] ?? en.errors.generic;
}
